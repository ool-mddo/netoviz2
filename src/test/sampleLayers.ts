import type { SchematicLayerInput } from '../render/layout/schematic/types'

/**
 * Nodes (names) and links between the nodes of layer1 of the sample topologies (topologies/<network>/<snapshot>/
 * topology.json of the playground): the data to test the inference of the schematic layout. IDs are `layer1/<name>`.
 */
type Sample = { nodes: string[]; links: Array<[string, string]> }

function layerOf({ nodes, links }: Sample): Pick<SchematicLayerInput, 'layer' | 'nodes' | 'links'> {
  return {
    layer: 'layer1',
    nodes: nodes.map((name) => ({ id: `layer1/${name}`, name, radius: 11 })),
    links: links.map(([source, target]) => ({ source: `layer1/${source}`, target: `layer1/${target}` })),
  }
}


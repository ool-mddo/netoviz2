const idOf = (layer: string, name: string) => `${layer}/${encodeURIComponent(name)}`

export function mddoFwLayer(layer: 'layer1' | 'layer2' | 'layer3'): StackLayer {
  const { nodes, links } = LAYERS[layer]!
  return {
    layer,
    nodes: nodes.map((name) => ({ id: idOf(layer, name), name, radius: 11 })),
    links: links.map(([a, b]) => ({ source: idOf(layer, a), target: idOf(layer, b) })),
  }
}

